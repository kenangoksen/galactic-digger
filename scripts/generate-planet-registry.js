#!/usr/bin/env node
/**
 * 🪐 Planet Registry Generator
 * 
 * Scans assets/images/sprites/planets/ for planet files and
 * auto-generates:
 *   1. assets/registry/planetSprites.js  (require map + animation metadata)
 *   2. assets/config/planets.json        (metadata array)
 * 
 * Naming conventions:
 *   - Static:   planet_01.png
 *   - Animated: planet_09_animated.png  (default 4x4 grid = 16 frames)
 *              planet_09_animated_6x3.png  (custom grid: 6 cols x 3 rows)
 * 
 * Usage:  node scripts/generate-planet-registry.js
 */

const fs   = require("fs");
const path = require("path");

// ── Paths ──
const SPRITES_DIR   = path.resolve(__dirname, "../assets/images/sprites/planets");
const REGISTRY_FILE = path.resolve(__dirname, "../assets/registry/planetSprites.js");
const CONFIG_FILE   = path.resolve(__dirname, "../assets/config/planets.json");

// ── Default planet names (cycling fallback) ──
const DEFAULT_NAMES = [
  "Dusty Rock", "Candy Crater", "Lava Puff", "Frost Pebble",
  "Neon Void", "Crystal Moon", "Iron Giant", "Solar Drift",
  "Plasma Core", "Shadow Reef", "Emerald Haze", "Crimson Dune",
  "Azure Depths", "Golden Rings", "Obsidian Peak", "Titanium Shell",
  "Quantum Flare", "Nebula Bloom", "Gravity Well", "Starfall Basin",
];

// ── Default animated sprite sheet settings ──
const DEFAULT_ANIM_COLS = 4;
const DEFAULT_ANIM_ROWS = 4;
const DEFAULT_ANIM_FPS  = 10;

// ── Scan & Parse ──
const allFiles = fs.readdirSync(SPRITES_DIR)
  .filter(f => /^planet_\d+.*\.png$/i.test(f))
  .sort((a, b) => {
    const numA = parseInt(a.match(/\d+/)[0], 10);
    const numB = parseInt(b.match(/\d+/)[0], 10);
    return numA - numB;
  });

if (allFiles.length === 0) {
  console.error("❌ No planet_XX.png files found in", SPRITES_DIR);
  process.exit(1);
}

// Parse each file
const entries = allFiles.map(filename => {
  // Check if animated: planet_09_animated.png or planet_09_animated_6x3.png
  const animMatch = filename.match(/^(planet_\d+)_animated(?:_(\d+)x(\d+))?\.png$/i);
  
  if (animMatch) {
    const id = animMatch[1]; // "planet_09"
    const cols = animMatch[2] ? parseInt(animMatch[2], 10) : DEFAULT_ANIM_COLS;
    const rows = animMatch[3] ? parseInt(animMatch[3], 10) : DEFAULT_ANIM_ROWS;
    return {
      id,
      filename,
      animated: true,
      cols,
      rows,
      frameCount: cols * rows,
      fps: DEFAULT_ANIM_FPS,
    };
  } else {
    const id = filename.replace(".png", ""); // "planet_01"
    return {
      id,
      filename,
      animated: false,
    };
  }
});

console.log(`🪐 Found ${entries.length} planet sprites:`);
entries.forEach(e => {
  if (e.animated) {
    console.log(`   🎞️  ${e.filename} (animated ${e.cols}x${e.rows} = ${e.frameCount} frames)`);
  } else {
    console.log(`   🖼️  ${e.filename} (static)`);
  }
});

// ── 1. Generate planetSprites.js ──
const requireLines = entries.map(e => {
  return `  "${e.filename}": require("../images/sprites/planets/${e.filename}"),`;
});

// Build animation metadata map
const animMetaLines = entries
  .filter(e => e.animated)
  .map(e => `  "${e.filename}": { cols: ${e.cols}, rows: ${e.rows}, frameCount: ${e.frameCount}, fps: ${e.fps} },`);

const registryContent = [
  "// ⚡ AUTO-GENERATED by scripts/generate-planet-registry.js",
  "// DO NOT EDIT MANUALLY — run: node scripts/generate-planet-registry.js",
  "",
  "export const PLANET_SPRITES = {",
  ...requireLines,
  "};",
  "",
  `export const PLANET_COUNT = ${entries.length};`,
  "",
  "// Animation metadata for animated sprite sheets",
  "export const PLANET_ANIM_META = {",
  ...animMetaLines,
  "};",
  "",
].join("\n");

fs.writeFileSync(REGISTRY_FILE, registryContent, "utf-8");
console.log(`\n✅ Generated ${REGISTRY_FILE}`);

// ── 2. Generate planets.json ──
let existingPlanets = [];
if (fs.existsSync(CONFIG_FILE)) {
  try {
    existingPlanets = JSON.parse(fs.readFileSync(CONFIG_FILE, "utf-8"));
  } catch (e) { /* ignore parse errors */ }
}

const existingMap = {};
existingPlanets.forEach(p => { existingMap[p.id] = p; });

const planetsConfig = entries.map((e, i) => {
  const existing = existingMap[e.id];
  const entry = {
    id: e.id,
    name: existing?.name || DEFAULT_NAMES[i % DEFAULT_NAMES.length],
    sprite: e.filename,
  };
  if (e.animated) {
    entry.animated = true;
    entry.cols = e.cols;
    entry.rows = e.rows;
    entry.frameCount = e.frameCount;
    entry.fps = e.fps;
  }
  return entry;
});

fs.writeFileSync(CONFIG_FILE, JSON.stringify(planetsConfig, null, 2) + "\n", "utf-8");
console.log(`✅ Generated ${CONFIG_FILE} (${planetsConfig.length} planets)`);

console.log("\n🚀 Done! Planet registry is up to date.");
